#!/usr/bin/env python3
"""Render the Homebrew formula and Scoop manifest for a published release.

The catalogs live in outpace-stream/homebrew-outpace and outpace-stream/scoop-outpace.
After a release is published, clone both repositories and refresh their manifests:

    gh release download vX.Y.Z --repo outpace-stream/outpace-engine --pattern SHA256SUMS --dir /tmp/sums
    python3 tools/release/package_manifests.py vX.Y.Z /tmp/sums/SHA256SUMS \
        --homebrew-root ../homebrew-outpace --scoop-root ../scoop-outpace

Open a PR in each catalog repository. Checksums always come from a published release.
"""
import argparse
import json
from pathlib import Path
import re

REPO = "https://github.com/outpace-stream/outpace-engine"
DESCRIPTION = "Open-source streaming engine for public Acestream content"
LICENSE = "AGPL-3.0-or-later"

# Homebrew (macOS and Linux) and Scoop (Windows) platforms -> release targets.
BREW = {
    ("macos", "arm"): "aarch64-apple-darwin",
    ("macos", "intel"): "x86_64-apple-darwin",
    ("linux", "arm"): "aarch64-unknown-linux-musl",
    ("linux", "intel"): "x86_64-unknown-linux-musl",
}
SCOOP = {
    "64bit": "x86_64-pc-windows-msvc",
    "arm64": "aarch64-pc-windows-msvc",
}


def parse_tag(tag: str) -> str:
    if not re.fullmatch(r"v(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)", tag):
        raise ValueError("Expected a stable release tag vX.Y.Z")
    return tag[1:]


def parse_sums(text: str) -> dict:
    sums = {}
    for line in text.splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  (\S+)", line)
        if not match or match[2] in sums:
            raise ValueError(f"Invalid or duplicate checksum line: {line!r}")
        sums[match[2]] = match[1]
    return sums


def asset(version: str, target: str, ext: str) -> str:
    return f"outpace-{version}-{target}.{ext}"


def url(version: str, name: str) -> str:
    return f"{REPO}/releases/download/v{version}/{name}"


def digest(sums: dict, name: str) -> str:
    if name not in sums:
        raise ValueError(f"SHA256SUMS has no entry for {name}")
    return sums[name]


def formula(version: str, sums: dict) -> str:
    def block(os_name: str) -> str:
        parts = []
        for cpu in ("arm", "intel"):
            name = asset(version, BREW[(os_name, cpu)], "tar.gz")
            parts.append(
                f"    on_{cpu} do\n"
                f'      url "{url(version, name)}"\n'
                f'      sha256 "{digest(sums, name)}"\n'
                f"    end"
            )
        return f"  on_{os_name} do\n" + "\n".join(parts) + "\n  end"

    return f"""# typed: false
# frozen_string_literal: true

# Generated by tools/release/package_manifests.py; do not edit by hand.
class Outpace < Formula
  desc "{DESCRIPTION}"
  homepage "{REPO}"
  license "{LICENSE}"

{block("macos")}
{block("linux")}

  def install
    bin.install "outpace"
  end

  # `brew services start outpace`: launchd on macOS, systemd on Linux.
  service do
    run [opt_bin/"outpace", "serve"]
    keep_alive crashed: true
    environment_variables OUTPACE_BIND: "127.0.0.1:6878", OUTPACE_RTMP_BIND: "127.0.0.1:1935"
    log_path var/"log/outpace.log"
    error_log_path var/"log/outpace.log"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/outpace --version")
  end
end
"""


def scoop(version: str, sums: dict) -> str:
    architecture = {}
    autoupdate = {}
    for arch, target in SCOOP.items():
        name = asset(version, target, "zip")
        architecture[arch] = {
            "url": url(version, name),
            "hash": digest(sums, name),
            "extract_dir": f"outpace-{version}-{target}",
        }
        autoupdate[arch] = {
            "url": url("$version", asset("$version", target, "zip")),
            "extract_dir": f"outpace-$version-{target}",
        }
    manifest = {
        "##": "Generated by tools/release/package_manifests.py; do not edit by hand.",
        "version": version,
        "description": DESCRIPTION,
        "homepage": REPO,
        "license": LICENSE,
        "architecture": architecture,
        "bin": "outpace.exe",
        "checkver": {"github": REPO},
        "autoupdate": {
            "architecture": autoupdate,
            "hash": {"url": "$baseurl/SHA256SUMS"},
        },
    }
    return json.dumps(manifest, indent=4) + "\n"


def render(tag: str, sums_text: str, homebrew_root: Path, scoop_root: Path) -> None:
    version = parse_tag(tag)
    sums = parse_sums(sums_text)
    # Validate both catalogs before writing either, so missing assets leave no partial update.
    brew_text = formula(version, sums)
    scoop_text = scoop(version, sums)
    (homebrew_root / "Formula").mkdir(parents=True, exist_ok=True)
    (scoop_root / "bucket").mkdir(parents=True, exist_ok=True)
    (homebrew_root / "Formula" / "outpace.rb").write_text(brew_text)
    (scoop_root / "bucket" / "outpace.json").write_text(scoop_text)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("tag")
    parser.add_argument("sha256sums", type=Path)
    parser.add_argument("--homebrew-root", type=Path, required=True)
    parser.add_argument("--scoop-root", type=Path, required=True)
    args = parser.parse_args()
    render(args.tag, args.sha256sums.read_text(), args.homebrew_root, args.scoop_root)
